//! Fixed-point clock geometry, without floating point on the MCU.
pub fn point(phase: u16, radius: i32) -> (i32, i32) {
    const P: [(i16, i16); 60] = [
        (0, -1000),
        (105, -995),
        (208, -978),
        (309, -951),
        (407, -914),
        (500, -866),
        (588, -809),
        (669, -743),
        (743, -669),
        (809, -588),
        (866, -500),
        (914, -407),
        (951, -309),
        (978, -208),
        (995, -105),
        (1000, 0),
        (995, 105),
        (978, 208),
        (951, 309),
        (914, 407),
        (866, 500),
        (809, 588),
        (743, 669),
        (669, 743),
        (588, 809),
        (500, 866),
        (407, 914),
        (309, 951),
        (208, 978),
        (105, 995),
        (0, 1000),
        (-105, 995),
        (-208, 978),
        (-309, 951),
        (-407, 914),
        (-500, 866),
        (-588, 809),
        (-669, 743),
        (-743, 669),
        (-809, 588),
        (-866, 500),
        (-914, 407),
        (-951, 309),
        (-978, 208),
        (-995, 105),
        (-1000, 0),
        (-995, -105),
        (-978, -208),
        (-951, -309),
        (-914, -407),
        (-866, -500),
        (-809, -588),
        (-743, -669),
        (-669, -743),
        (-588, -809),
        (-500, -866),
        (-407, -914),
        (-309, -951),
        (-208, -978),
        (-105, -995),
    ];
    let phase = usize::from(phase % 3600);
    let i = phase / 60;
    let f = (phase % 60) as i32;
    let a = P[i];
    let b = P[(i + 1) % 60];
    (
        (i32::from(a.0) * (60 - f) + i32::from(b.0) * f) * radius / 60000,
        (i32::from(a.1) * (60 - f) + i32::from(b.1) * f) * radius / 60000,
    )
}
