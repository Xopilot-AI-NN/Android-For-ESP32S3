// Compile official Material Symbols Rounded SVGs into 24px 4-bit alpha masks.
// Normal builds are offline. Use --fetch to refresh from the pinned Google commit.
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const revision = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7';
const root = path.resolve(__dirname, '../src/material/symbols');
const symbols = {
    Wifi: 'wifi', Bluetooth: 'bluetooth', Dnd: 'do_not_disturb_on',
    Airplane: 'flight', Sun: 'light_mode', Settings: 'settings',
    Bell: 'notifications', Clock: 'schedule', Play: 'play_arrow', Pause: 'pause',
    Info: 'info', Grid: 'apps', Assistant: 'auto_awesome',
    Back: 'arrow_back', Lock: 'lock', Sound: 'volume_up',
    Person: 'accessibility_new', Connectivity: 'settings_input_antenna',
    Gestures: 'gesture', Developer: 'developer_mode', Search: 'search',
    Flashlight: 'flashlight_on', Previous: 'skip_previous', Next: 'skip_next',
    Timer: 'timer', Alarm: 'alarm', Devices: 'devices',
};
fs.mkdirSync(root, {recursive: true});
const fetch = process.argv.includes('--fetch');
const base = `https://raw.githubusercontent.com/google/material-design-icons/${revision}`;
let data = [];
for (const [key, name] of Object.entries(symbols)) {
    const file = path.join(root, `${name}.svg`);
    if (fetch) cp.execFileSync('curl', ['-fLsS', '--max-time', '30',
        `${base}/symbols/web/${name}/materialsymbolsrounded/${name}_fill1_24px.svg`, '-o', file]);
    const pixels = cp.execFileSync('magick', ['-background', 'none', '-density', '384', file,
        '-resize', '24x24!', '-alpha', 'extract', '-depth', '8', 'gray:-']);
    if (pixels.length !== 576 || !pixels.some(p => p > 0) || !pixels.some(p => p === 0)) {
        throw new Error(`Invalid icon mask: ${name}`);
    }
    for (let i = 0; i < pixels.length; i += 2) {
        data.push((Math.round(pixels[i] / 17) << 4) | Math.round(pixels[i + 1] / 17));
    }
}
if (fetch) cp.execFileSync('curl', ['-fLsS', '--max-time', '30', `${base}/LICENSE`, '-o', path.join(root, 'LICENSE')]);
fs.writeFileSync(path.join(root, 'atlas.bin'), Buffer.from(data));
fs.writeFileSync(path.join(root, 'mod.rs'), `// Generated by tools/build_ui_icons.cjs; see SOURCE.md for provenance.\n#[derive(Clone, Copy)]\n#[repr(usize)]\npub(super) enum Symbol {\n${Object.keys(symbols).map(n => `    ${n},`).join('\n')}\n}\npub(super) const SIZE: usize = 24;\npub(super) const ATLAS: &[u8; ${data.length}] = include_bytes!("atlas.bin");\n`);
console.log(`Built ${Object.keys(symbols).length} official symbols (${data.length} bytes)`);
